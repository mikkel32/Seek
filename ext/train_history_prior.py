"""Fit an opening-separated conditional move model to Stockfish's recorded quiet moves."""
import argparse
import gzip
import json
from pathlib import Path

import chess
import numpy as np
from scipy.optimize import minimize

from fit_readout import holdout
from readout_arena import opening_key


def positions(archive):
    splits = [[], []]
    seen = [set(), set()]
    with gzip.open(archive, "rt") as stream:
        for line in stream:
            game = json.loads(line)
            board = chess.Board(game["fen"])
            part = int(holdout(game["fen"]))
            for uci in game["moves"]:
                move = chess.Move.from_uci(uci)
                if board.turn != game["us_white"] and not board.is_capture(move) and not move.promotion:
                    key = opening_key(board.fen())
                    if key not in seen[part]:
                        flip = 0 if board.turn == chess.WHITE else 56
                        encode = lambda m: (m.from_square ^ flip) * 64 + (m.to_square ^ flip)
                        choices = [encode(move)] + [
                            encode(m) for m in board.legal_moves
                            if m != move and not board.is_capture(m) and not m.promotion]
                        if len(choices) > 1:
                            splits[part].append((key, min(3, board.occupied.bit_count() // 8), choices))
                            seen[part].add(key)
                board.push(move)
    splits[1] = [row for row in splits[1] if row[0] not in seen[0]]
    return splits


def pack(rows):
    starts = np.cumsum([0] + [len(row[2]) for row in rows[:-1]])
    moves = np.array([m for _, _, choices in rows for m in choices])
    phases = np.array([p for _, p, choices in rows for _ in choices])
    groups = np.repeat(np.arange(len(rows)), np.diff(np.r_[starts, len(moves)]))
    return starts, moves, phases * 4096 + moves, groups


def objective(params, batch, regularize):
    starts, moves, by_phase, groups = batch
    logits = params[moves] + params[4096 + by_phase]
    maxima = np.maximum.reduceat(logits, starts)
    weights = np.exp(logits - maxima[groups])
    sums = np.add.reduceat(weights, starts)
    loss = (np.log(sums) + maxima - logits[starts]).mean()
    grad = weights / sums[groups]
    grad[starts] -= 1
    gradient = np.r_[np.bincount(moves, grad, minlength=4096),
                     np.bincount(by_phase, grad, minlength=4 * 4096)] / len(starts)
    if regularize:
        penalty = np.r_[np.full(4096, 1.5), np.full(4 * 4096, 5.)] / len(starts)
        loss += .5 * (penalty * params) @ params
        gradient += penalty * params
    return loss, gradient


def train(archive, output):
    tr, va = positions(archive)
    train_rows, valid_rows = pack(tr), pack(va)
    initial = np.zeros(5 * 4096)
    result = minimize(objective, initial, args=(train_rows, True), jac=True, method="L-BFGS-B",
                      options={"maxiter": 300, "gtol": 1e-7, "ftol": 1e-11})
    if not result.success:
        raise RuntimeError(result.message)
    scores = result.x[:4096] + result.x[4096:].reshape(4, 4096)
    table = np.rint(256 * np.clip(scores, -4, 4)).astype(np.int16)
    # Score exactly the clipped, quantized table that will be used in search.
    quantized = np.r_[np.zeros(4096), table.ravel() / 256.]
    print(json.dumps(dict(training_positions=len(tr), validation_positions=len(va),
                          uniform_loss=objective(initial, valid_rows, False)[0],
                          trained_loss=objective(quantized, valid_rows, False)[0])))
    with output.open("x") as out:
        print("/* Generated by ext/train_history_prior.py. */", file=out)
        print("static const short quiet_move_prior[4][4096] = {", file=out)
        for phase in table:
            print("{", file=out)
            for chunk in phase.reshape(64,64):
                print(",".join(map(str,chunk)) + ",", file=out)
            print("},", file=out)
        print("};", file=out)


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("archive", type=Path)
    parser.add_argument("output", type=Path, help="new path for history_prior.h")
    args = parser.parse_args()
    train(args.archive, args.output)
