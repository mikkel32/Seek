"""Learn a soft clock allocation from move times in the 10+0.1 BIGS–Stockfish archive."""
import argparse
import gzip
import json
import math
from pathlib import Path

import chess
import numpy as np

from fit_readout import holdout


EDGES = (15, 25, 40, 60, 90)
FEATURES = ('intercept', 'log legal moves', 'log captures', 'in check', 'remaining pieces', 'queens', 'forced reply')


def examples(archive):
    rows = [[], []]
    with gzip.open(archive, 'rt') as stream:
        for line in stream:
            game = json.loads(line)
            if len(game['ms']) != len(game['moves']):
                raise ValueError('Missing move times in archive')
            split = rows[holdout(game['fen'])]
            board = chess.Board(game['fen'])
            remaining = 10_000
            for move, elapsed in zip(game['moves'], game['ms']):
                if board.turn != game['us_white']:
                    legal = list(board.legal_moves)
                    captures = sum(board.is_capture(m) for m in legal)
                    group = sum(board.fullmove_number > bound for bound in EDGES)
                    target = math.log(max(elapsed, 2) / (max(remaining, 1) / 20 + 75))
                    split.append([group, target, 1, math.log1p(len(legal)), math.log1p(captures),
                                  board.is_check(), board.occupied.bit_count() / 16,
                                  board.queens.bit_count(), len(legal) == 1])
                    remaining += 100 - elapsed
                board.push_uci(move)
    return [np.array(group) for group in rows]


def fit(archive, output):
    train, valid = examples(archive)
    group = train[:, 0].astype(int)
    y, x = train[:, 1], train[:, 2:]
    means = np.stack([x[group == i].mean(axis=0) for i in range(6)])
    targets = np.array([y[group == i].mean() for i in range(6)])
    centered = x - means[group]
    weights = np.linalg.solve(centered.T @ centered + np.eye(x.shape[1]) * 20,
                              centered.T @ (y - targets[group]))
    # Retain mean multiplier 1 in each training phase after clipping and shrinkage.
    pred = np.clip(centered @ weights, -.90, .60)
    normalizers = [np.exp(.6 * pred[group == i]).mean() for i in range(6)]
    vg = valid[:, 0].astype(int)
    phase_errors = valid[:, 1] - targets[vg]
    errors = phase_errors - (valid[:, 2:] - means[vg]) @ weights
    metrics = dict(training=len(train), heldout=len(valid), features=FEATURES,
                   valid_logtime_rmse_phase=float(np.mean(phase_errors ** 2) ** .5),
                   valid_logtime_rmse_structural=float(np.mean(errors ** 2) ** .5))
    def c_values(row):
        return ', '.join(f'{v:.10g}' for v in row)
    with output.open('x') as header:
        print('/* Generated by ext/train_clock.py from Stockfish 14.1 move times. */', file=header)
        print('static const int phase_edges[5] = {' + c_values(EDGES) + '};', file=header)
        print('static const double clock_weights[7] = {' + c_values(weights) + '};', file=header)
        print('static const double feature_means[6][7] = {', file=header)
        for row in means:
            print('    {' + c_values(row) + '},', file=header)
        print('};', file=header)
        print('static const double phase_normalizer[6] = {' + c_values(normalizers) + '};', file=header)
    return metrics


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('archive', type=Path)
    parser.add_argument('output', type=Path, help='New path for clock_weights.h')
    args = parser.parse_args()
    print(json.dumps(fit(args.archive, args.output)))
